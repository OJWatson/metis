"""Publish CI-generated notebooks to the dedicated Colab branch."""

import argparse
from pathlib import Path
import re
import shutil
import subprocess


def publish(source: Path, destination: Path, revision: str) -> None:
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("Expected a full source commit SHA")
    source, destination = source.resolve(), destination.resolve()
    notebooks = sorted(source.rglob("*.ipynb"))
    if not notebooks:
        raise ValueError("No executed notebooks to publish")
    if destination.exists():
        raise FileExistsError(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)

    def checkout_git(*args: str) -> str:
        return subprocess.check_output(["git", *args], text=True).strip()

    def git(*args: str) -> str:
        return subprocess.check_output(
            ["git", "-C", str(destination), *args], text=True,
        ).strip()

    # A worktree shares origin and checkout's authentication. In checkout v6,
    # credentials live in a separate file included for the checkout/worktrees;
    # do not read, duplicate, or put the token into a command-line argument.
    exists = bool(checkout_git("ls-remote", "--heads", "origin", "notebooks"))
    if exists:
        checkout_git("fetch", "--depth=1", "origin", "notebooks")
    checkout_git("worktree", "add", "--detach", str(destination),
                 "FETCH_HEAD" if exists else "HEAD")
    try:
        if not exists:
            git("switch", "--orphan", "notebooks")
        git("rm", "-r", "--ignore-unmatch", "--", ".")
        for notebook in notebooks:
            target = destination / notebook.relative_to(source)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(notebook, target)
        (destination / "README.md").write_text(
            "# Executed METIS tutorials\n\n"
            "Generated by the documentation workflow. Edit tutorial sources on `main`.\n\n"
            f"Source revision: `{revision}`.\n\n"
            "[Read the tutorials](https://ojwatson.github.io/metis/). "
            "Their Open in Colab buttons load the notebooks on this branch.\n"
        )
        git("add", ".")
        if git("status", "--porcelain"):
            git("-c", "user.name=github-actions[bot]",
                "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com",
                "-c", "commit.gpgSign=false",
                "commit", "-m", f"Publish tutorials from {revision[:12]}")
            git("push", "origin", "HEAD:refs/heads/notebooks")
    finally:
        checkout_git("worktree", "remove", "--force", str(destination))
    print(f"Published {len(notebooks)} notebooks from {revision}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    parser.add_argument("--revision", required=True)
    args = parser.parse_args()
    publish(args.source, args.destination, args.revision)
